//! Generate static shell code from the same built Clap tree as the parser.
//! Completion never runs Ibis, reads a library, or guesses citation keys.
use clap::{Arg, Command, ValueHint};

fn quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "'\\''"))
}

fn flags(arg: &Arg) -> Vec<String> {
    arg.get_long()
        .map(|name| format!("--{name}"))
        .into_iter()
        .chain(arg.get_short().map(|name| format!("-{name}")))
        .collect()
}

fn values(arg: &Arg) -> Vec<String> {
    arg.get_possible_values()
        .into_iter()
        .filter(|value| !value.is_hide_set())
        .map(|value| value.get_name().to_owned())
        .collect()
}

fn file_value(arg: &Arg) -> bool {
    matches!(
        arg.get_value_hint(),
        ValueHint::AnyPath | ValueHint::FilePath | ValueHint::DirPath
    )
}

fn takes_value(arg: &Arg) -> bool {
    arg.get_num_args().is_some_and(|range| range.takes_values())
}

fn scopes(root: &Command) -> impl Iterator<Item = (&str, &Command)> {
    std::iter::once(("", root)).chain(
        root.get_subcommands()
            .filter(|sub| !sub.is_hide_set())
            .map(|sub| (sub.get_name(), sub)),
    )
}

fn words(command: &Command) -> Vec<String> {
    command
        .get_subcommands()
        .filter(|sub| !sub.is_hide_set())
        .map(|sub| sub.get_name().to_owned())
        .chain(command.get_arguments().filter(|arg| !arg.is_hide_set()).flat_map(flags))
        .chain(command.get_positionals().flat_map(values))
        .collect()
}

pub(super) fn generate(mut root: Command, shell: &str) -> String {
    root.build();
    match shell {
        "bash" => bash(&root),
        "zsh" => zsh(&root),
        "fish" => fish(&root),
        _ => unreachable!("Clap validates the completion shell"),
    }
}

// Bash and zsh share a small metadata lookup. All names and values come from
// Clap; even the root options whose next word must be skipped are generated.
fn lookup(root: &Command) -> String {
    let mut script =
        String::from("_ibis_values() {\n  ibis_values='' ibis_files=0 ibis_takes_value=0\n  case \"$1:$2\" in\n");
    for (name, command) in scopes(root) {
        for arg in command.get_arguments().filter(|arg| !arg.is_hide_set()) {
            let patterns: Vec<_> = flags(arg)
                .into_iter()
                .map(|flag| quote(&format!("{name}:{flag}")))
                .collect();
            if patterns.is_empty() {
                continue;
            }
            script.push_str(&format!(
                "    {}) ibis_values={}; ibis_files={}; ibis_takes_value={} ;;\n",
                patterns.join("|"),
                quote(&values(arg).join(" ")),
                u8::from(file_value(arg)),
                u8::from(takes_value(arg))
            ));
        }
    }
    script.push_str("  esac\n}\n");
    script
}

fn command_words(root: &Command) -> String {
    let mut script = String::from("_ibis_words() {\n  case \"$1\" in\n");
    for (name, command) in scopes(root) {
        script.push_str(&format!(
            "    {}) ibis_words={} ;;\n",
            quote(name),
            quote(&words(command).join(" "))
        ));
    }
    script.push_str("    *) ibis_words='' ;;\n  esac\n}\n");
    script
}

fn bash(root: &Command) -> String {
    let mut script = String::from("# Generated by ibis completions bash.\n");
    script.push_str(&lookup(root));
    script.push_str(&command_words(root));
    script.push_str(
        r#"_ibis() {
  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"
  local cmd='' skip=0 i word flag prefix='' ibis_values ibis_files ibis_takes_value ibis_words
  COMPREPLY=()
  for ((i=1; i<COMP_CWORD; i++)); do
    word="${COMP_WORDS[i]}"
    if ((skip)); then [[ "$word" == '=' ]] || skip=0; continue; fi
    if [[ "$word" == --*=* ]]; then continue; fi
    _ibis_values '' "$word"
    if ((ibis_takes_value)); then skip=1; continue; fi
    if [[ "$word" != -* ]]; then cmd="$word"; break; fi
  done
  flag="$prev"
  if [[ "$prev" == '=' && COMP_CWORD -ge 2 ]]; then flag="${COMP_WORDS[COMP_CWORD-2]}"; fi
  if [[ "$cur" == --*=* ]]; then
    flag="${cur%%=*}"; prefix="$flag="; cur="${cur#*=}"
  fi
  _ibis_values "$cmd" "$flag"
  if ((ibis_takes_value)); then
    if [[ -n "$ibis_values" ]]; then
      while IFS= read -r word; do COMPREPLY+=("$prefix$word"); done < <(compgen -W "$ibis_values" -- "$cur")
    elif ((ibis_files)); then
      while IFS= read -r word; do COMPREPLY+=("$prefix$word"); done < <(compgen -f -- "$cur")
      # Preserve spaces and let Bash quote filenames. This is optional outside a completion callback.
      compopt -o filenames 2>/dev/null || :
    fi
    return 0
  fi
  _ibis_words "$cmd"
  while IFS= read -r word; do COMPREPLY+=("$word"); done < <(compgen -W "$ibis_words" -- "$cur")
  return 0
}
complete -F _ibis ibis
"#,
    );
    script.trim_end_matches('\n').into()
}

fn zsh(root: &Command) -> String {
    let mut script = String::from("#compdef ibis\n# Generated by ibis completions zsh.\n");
    script.push_str(&lookup(root));
    script.push_str(&command_words(root));
    script.push_str(
        r#"_ibis() {
  local cmd='' skip=0 i word flag prefix=''
  local ibis_values ibis_files ibis_takes_value ibis_words
  local cur="${words[CURRENT]}" prev="${words[CURRENT-1]}"
  local -a candidates
  for ((i=2; i<CURRENT; i++)); do
    word="${words[i]}"
    if ((skip)); then [[ "$word" == '=' ]] || skip=0; continue; fi
    if [[ "$word" == --*=* ]]; then continue; fi
    _ibis_values '' "$word"
    if ((ibis_takes_value)); then skip=1; continue; fi
    if [[ "$word" != -* ]]; then cmd="$word"; break; fi
  done
  flag="$prev"
  if [[ "$cur" == --*=* ]]; then
    flag="${cur%%=*}"; prefix="$flag="
    compset -P '*='
  fi
  _ibis_values "$cmd" "$flag"
  if ((ibis_takes_value)); then
    if [[ -n "$ibis_values" ]]; then
      candidates=( ${=ibis_values} )
      compadd -- "${candidates[@]}"
    elif ((ibis_files)); then
      _files
    fi
    return 0
  fi
  _ibis_words "$cmd"
  candidates=( ${=ibis_words} )
  compadd -- "${candidates[@]}"
}
compdef _ibis ibis
"#,
    );
    script.trim_end_matches('\n').into()
}

fn fish(root: &Command) -> String {
    let mut script = String::from(
        "# Generated by ibis completions fish.\nfunction __ibis_command\n  set -l words (commandline -opc)\n  set -l skip 0\n  for word in $words[2..-1]\n    if test $skip -eq 1\n      set skip 0\n      continue\n    end\n    if string match -q -- '--*=*' $word\n      continue\n    end\n    switch $word\n",
    );
    for arg in root.get_arguments().filter(|arg| takes_value(arg)) {
        let patterns = flags(arg)
            .iter()
            .map(|flag| fish_quote(flag))
            .collect::<Vec<_>>()
            .join(" ");
        if !patterns.is_empty() {
            script.push_str(&format!(
                "      case {patterns}\n        set skip 1\n        continue\n"
            ));
        }
    }
    script.push_str(
        "    end\n    if not string match -q -- '-*' $word\n      echo $word\n      return\n    end\n  end\nend\n",
    );
    script.push_str("complete -c ibis -f\n");
    for (name, command) in scopes(root) {
        let condition = if name.is_empty() {
            "not string length -q -- (__ibis_command)".into()
        } else {
            format!("contains -- {} (__ibis_command)", fish_quote(name))
        };
        for subcommand in command.get_subcommands().filter(|sub| !sub.is_hide_set()) {
            script.push_str(&format!(
                "complete -c ibis -n {} -a {} -d {}\n",
                fish_quote(&condition),
                fish_quote(subcommand.get_name()),
                fish_quote(&subcommand.get_about().map(ToString::to_string).unwrap_or_default())
            ));
        }
        for arg in command.get_arguments().filter(|arg| !arg.is_hide_set()) {
            if flags(arg).is_empty() {
                continue;
            }
            script.push_str(&format!("complete -c ibis -n {}", fish_quote(&condition)));
            if let Some(long) = arg.get_long() {
                script.push_str(&format!(" -l {}", fish_quote(long)));
            }
            if let Some(short) = arg.get_short() {
                script.push_str(&format!(" -s {}", fish_quote(&short.to_string())));
            }
            if takes_value(arg) {
                script.push_str(" -r");
            }
            if file_value(arg) {
                script.push_str(" -F");
            }
            let choices = values(arg);
            if !choices.is_empty() {
                script.push_str(&format!(" -a {}", fish_quote(&choices.join(" "))));
            }
            script.push_str(&format!(
                " -d {}\n",
                fish_quote(&arg.get_help().map(ToString::to_string).unwrap_or_default())
            ));
        }
        // Finite positional values (currently the shell for `completions`).
        for arg in command.get_positionals() {
            let choices = values(arg);
            if !choices.is_empty() {
                script.push_str(&format!(
                    "complete -c ibis -n {} -a {}\n",
                    fish_quote(&condition),
                    fish_quote(&choices.join(" "))
                ));
            }
        }
    }
    script.trim_end_matches('\n').into()
}

fn fish_quote(text: &str) -> String {
    format!("'{}'", text.replace('\\', "\\\\").replace('\'', "\\'"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_new_command_option_and_enum_flow_from_clap_into_every_shell() {
        let command = super::super::command().subcommand(
            Command::new("invented-command").arg(
                Arg::new("invented-option")
                    .long("invented-option")
                    .value_parser(["invented-value"]),
            ),
        );
        for shell in ["bash", "zsh", "fish"] {
            let script = generate(command.clone(), shell);
            for word in ["invented-command", "invented-option", "invented-value"] {
                assert!(script.contains(word), "{shell}: {word}");
            }
        }
    }
}

#!/usr/bin/env node
// Report changes in the generated public contract (decision 0028).
// Use --base REF for an offline comparison, or --published in the advisory workflow.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { isDeepStrictEqual } from "node:util";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const CLI = "fixtures/cli-surface.json";
const DOCS = "docs/cli.md";

// Retain exact JSON numbers, including integers larger than Number.MAX_SAFE_INTEGER.
const parse = (text) => JSON.parse(text, (_key, value, { source }) =>
  typeof value === "number" && JSON.stringify(value) !== source ? JSON.rawJSON(source) : value);
const describe = (value) => JSON.stringify(value);
const keyed = (entries, key) => {
  if (!Array.isArray(entries) || entries.some((entry) => typeof entry?.[key] !== "string")) return entries;
  const map = Object.fromEntries(entries.map((entry) => [entry[key], entry]));
  return Object.keys(map).length === entries.length ? map : entries;
};

function section(text, begin, end) {
  const start = text.indexOf(begin);
  const stop = text.indexOf(end);
  if (start < 0 || stop < start) throw new Error(`Missing generated section ${begin} in ${DOCS}`);
  return text.slice(start + begin.length, stop).trim();
}

// Earlier releases only recorded the generated help and exit tables. Compare
// those same tables on both sides so unrecorded flag details remain unknown.
function cliHelp(text) {
  const options = section(text, "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->", "<!-- End of generated options. -->");
  const commands = Object.create(null);
  let command;
  for (const line of options.split("\n")) {
    const heading = /^\*\*(?:`ibis ([^`]+)`|(Every command))\*\*:?\s*(.*)$/.exec(line);
    if (heading) {
      command = { description: heading[3], arguments: Object.create(null) };
      commands[heading[1] ?? heading[2]] = command;
      continue;
    }
    const row = /^\| `([^`]+)` \| (.*) \|$/.exec(line);
    if (row && command) {
      const [, spelling, help] = row;
      command.arguments[spelling.split(" ")[0].replace(/…$/, "")] = { spelling, help };
    }
  }
  const errors = section(text, "<!-- gen:errors -->", "<!-- /gen:errors -->");
  return {
    commands: { ...commands },
    errors: Object.fromEntries([...errors.matchAll(/^\| (\d+) \| `([^`]+)` \|$/gm)].map(([, exit, code]) => [code, Number(exit)])),
  };
}

function contract(read, detailedCli) {
  const methods = parse(read("fixtures/cli-schema.json"));
  const cli = detailedCli ? parse(read(CLI)) : cliHelp(read(DOCS));
  return {
    "Engine schema": parse(read("fixtures/engine-contract.schema.json")),
    "Method schemas": { ...methods, data: keyed(methods.data, "method") },
    "MCP tools": keyed(parse(read("fixtures/mcp-tools.json")), "name"),
    "CLI": { ...cli, errors: keyed(cli.errors, "code") },
  };
}

const escapePath = (part) => part.replaceAll("~", "~0").replaceAll("/", "~1");
const object = (value) => value !== null && typeof value === "object" && !Array.isArray(value) && !JSON.isRawJSON(value);

// The same comparison applies to every artifact. Reference strings and their
// definitions are both in the tree, so changes to either are visible without
// expanding references. Array order is retained, including tuple positions.
function diff(before, after, path, changes) {
  if (before === undefined) {
    changes.added.push(`${path}  ${describe(after)}`);
  } else if (after === undefined) {
    changes.removed.push(`${path}  ${describe(before)}`);
  } else if (object(before) && object(after)) {
    for (const key of [...new Set([...Object.keys(before), ...Object.keys(after)])].sort()) {
      diff(Object.hasOwn(before, key) ? before[key] : undefined, Object.hasOwn(after, key) ? after[key] : undefined, `${path}/${escapePath(key)}`, changes);
    }
  } else if (Array.isArray(before) && Array.isArray(after)) {
    // Match an unchanged prefix and suffix before comparing positions. An
    // insertion near the front should not report every following item changed.
    let start = 0;
    let oldEnd = before.length;
    let newEnd = after.length;
    while (start < Math.min(oldEnd, newEnd) && isDeepStrictEqual(before[start], after[start])) start++;
    while (oldEnd > start && newEnd > start && isDeepStrictEqual(before[oldEnd - 1], after[newEnd - 1])) {
      oldEnd--;
      newEnd--;
    }
    for (let index = start; index < Math.max(oldEnd, newEnd); index++) {
      diff(index < oldEnd ? before[index] : undefined, index < newEnd ? after[index] : undefined, `${path}/${index}`, changes);
    }
  } else if (!isDeepStrictEqual(before, after)) {
    changes.changed.push(`${path}  ${describe(before)} → ${describe(after)}`);
  }
}


const markdownCode = (line) => {
  const fence = "`".repeat(1 + Math.max(0, ...(line.match(/`+/g) ?? []).map((run) => run.length)));
  return `${fence} ${line} ${fence}`;
};

/** The same report goes to the CI summary and the release notes. */
export function report(base, readBefore, readAfter, { includeUnchanged = true } = {}) {
  const detailedCli = readBefore(CLI) !== undefined;
  const before = contract(readBefore, detailedCli);
  const after = contract(readAfter, detailedCli);
  const changes = { added: [], removed: [], changed: [] };
  for (const name of Object.keys(before)) diff(before[name], after[name], `${name} `, changes);
  if (!includeUnchanged && Object.values(changes).every((lines) => lines.length === 0)) return "";
  const groups = Object.entries(changes).map(([kind, lines]) => [kind[0].toUpperCase() + kind.slice(1), lines]);
  const summary = `Compared with ${markdownCode(base)}. ${Object.entries(changes).map(([kind, lines]) => `${lines.length} ${kind}`).join(", ")}.`;
  const coverage = detailedCli ? [] : ["", "The baseline records only the generated CLI help and exit tables. Detailed CLI flags, aliases, arity and requiredness need a published snapshot."];
  return [
    "**Contract changes**", "", summary, ...coverage,
    ...groups.flatMap(([label, lines]) => lines.length ? ["", `**${label}**`, "", ...lines.map((line) => `- ${markdownCode(line)}`)] : []),
    "",
  ].join("\n");
}

const run = (command, args) => execFileSync(command, args, {
  cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 << 20,
});
const git = (...args) => run("git", args);

function publishedBase() {
  const tag = run("gh", ["api", `repos/${process.env.GITHUB_REPOSITORY}/releases/latest`, "--jq",
    "select(.draft == false and .prerelease == false) | .tag_name"]).trim();
  if (!/^v\d+\.\d+\.\d+$/.test(tag)) throw new Error("No published numbered release was found");
  const ref = `refs/tags/${tag}`;
  git("fetch", "--quiet", "--no-tags", "--depth=1", "origin", `${ref}:${ref}`);
  return ref;
}

function main(args) {
  const options = args[0] === "--published" ? 1 : 2;
  if ((args[0] !== "--published" && (args[0] !== "--base" || !args[1])) ||
      (args.length !== options && !(args.length === options + 2 && args[options] === "--notes" && args[options + 1]))) {
    throw new Error("Usage: node scripts/contract-compat.mjs (--base REF | --published) [--notes FILE]");
  }
  const base = args[0] === "--published" ? publishedBase() : args[1];
  const sha = git("rev-parse", "--verify", "--end-of-options", `${base}^{commit}`).trim();
  const hasCli = git("ls-tree", "--name-only", sha, "--", CLI).trim() === CLI;
  const notes = args[options + 1];
  const text = report(
    base.replace(/^refs\/tags\//, ""),
    (path) => (path === CLI && !hasCli ? undefined : git("show", `${sha}:${path}`)),
    (path) => readFileSync(new URL(path, root), "utf8"),
    { includeUnchanged: !notes },
  );
  if (notes) writeFileSync(notes, text);
  else process.stdout.write(text);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`Contract report skipped: ${error.message}`);
    process.exitCode = 1;
  }
}

#!/usr/bin/env node
// Compare the public contract with the newest release (decision 0028):
//   node scripts/contract-compat.mjs              # against the newest v* tag here
//   node scripts/contract-compat.mjs --base REF   # against any commit
// The contract is what tools built on Ibis read: the engine schema, each
// method's parameters and result, the MCP tools, and the CLI's commands,
// options and exit codes. Every difference is reported as additive or
// breaking. Before 1.0 nothing fails; see BLOCKING below.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/** The files the contract is read from. */
export const FILES = ["fixtures/engine-contract.schema.json", "fixtures/cli-schema.json", "fixtures/mcp-tools.json", "docs/cli.md"];

// --- Reading -----------------------------------------------------------------

const OPTIONS = ["<!-- Generated by node scripts/gen.mjs from the command line's own options. -->", "<!-- End of generated options. -->"];
const ERRORS = ["<!-- gen:errors -->", "<!-- /gen:errors -->"];

function between(text, [begin, end]) {
  const start = text.indexOf(begin);
  const stop = text.indexOf(end);
  if (start < 0 || stop < start) throw new Error(`docs/cli.md needs ${begin} before ${end}`);
  return text.slice(start + begin.length, stop);
}

/**
 * Each command's options (`--name` → takes a value), how many positional
 * arguments it lists, and each error code's exit. A row it cannot read fails.
 */
export function cliSurface(markdown) {
  const commands = new Map();
  let current = null;
  for (const line of between(markdown, OPTIONS).split("\n")) {
    const heading = line.match(/^\*\*(?:`ibis ([^`]+)`|Every command)\*\*/);
    if (heading) {
      current = { options: new Map(), positionals: 0 };
      commands.set(heading[1] ?? "*", current);
      continue;
    }
    if (!line.startsWith("| `")) continue;
    const option = line.match(/^\| `(--?[\w-]+)( [^`]*)?` \|/);
    if (option && current) current.options.set(option[1], Boolean(option[2]));
    else if (/^\| `[A-Z][A-Z_]*…?` \|/.test(line) && current) current.positionals++;
    else throw new Error(`docs/cli.md: cannot read the option row ${line}`);
  }
  const exits = new Map();
  for (const [, exit, code] of between(markdown, ERRORS).matchAll(/^\| (\d+) \| `([^`]+)` \|$/gm)) exits.set(code, Number(exit));
  return { commands, exits };
}

/** The parsed contract files, with the one contract version they all state. */
export function contract(texts) {
  const engine = JSON.parse(texts[FILES[0]]);
  const cli = JSON.parse(texts[FILES[1]]);
  const mcp = JSON.parse(texts[FILES[2]]);
  const versions = new Set([cli.ibis, engine.$defs?.EnvelopeVersion?.const, ...cli.data.map((method) => method.contract)]);
  if (versions.size !== 1 || !Number.isInteger(cli.ibis)) {
    throw new Error(`the contract files disagree on the contract version: ${[...versions].join(", ")}`);
  }
  return { version: cli.ibis, engine, cli, mcp, surface: cliSurface(texts[FILES[3]]) };
}

// --- Comparing schemas -------------------------------------------------------
//
// What Ibis accepts (input) may only grow; what it sends (output) may only
// shrink, except for what 0028 has clients accept: response fields they do not
// know, and values they do not know in an enumeration. A removed or renamed
// value breaks either way, and anything not understood counts as breaking.

const IGNORED = new Set(["description", "title", "$schema", "examples", "deprecated", "readOnly", "writeOnly", "$comment"]);
const BRANCHING = new Set(["oneOf", "anyOf", "enum", "const", "type", "$ref", "$defs"]);
const HANDLED = new Set([
  ...BRANCHING,
  "properties",
  "required",
  "additionalProperties",
  "items",
  "prefixItems",
  "default",
  "minimum",
  "maximum",
  "minItems",
  "maxItems",
  "minLength",
  "maxLength",
  "minProperties",
  "maxProperties",
  "pattern",
  "format",
]);
const UPPER = ["maximum", "maxItems", "maxLength", "maxProperties"];
const LOWER = ["minimum", "minItems", "minLength", "minProperties"];
const KINDS = ["string", "integer", "number", "boolean", "null", "array", "object"];

const show = (value) => JSON.stringify(value);

function resolve(document, schema) {
  let name = null;
  const seen = new Set();
  while (schema && typeof schema === "object" && schema.$ref) {
    const match = schema.$ref.match(/^#\/\$defs\/(.+)$/);
    if (!match || !document.$defs?.[match[1]] || seen.has(match[1])) throw new Error(`cannot follow ${schema.$ref}`);
    seen.add(match[1]);
    name = match[1];
    schema = document.$defs[name];
  }
  return { name, schema };
}

/** One schema as its alternatives: literal values, and branches by JSON kind. */
function alternatives(document, schema, inherited = {}) {
  const found = { literals: new Map(), branches: [], any: false };
  const add = (schema, shared) => {
    schema = resolve(document, schema).schema;
    if (schema === true || schema === undefined || (schema && Object.keys(schema).every((key) => IGNORED.has(key) || key.startsWith("x-")))) {
      if (!Object.keys(shared).length) return void (found.any = true);
    }
    if (schema === false) return;
    for (const keyword of ["oneOf", "anyOf"]) {
      if (!schema[keyword]) continue;
      const { [keyword]: variants, ...rest } = schema;
      const common = { ...shared, ...strip(rest) };
      for (const variant of variants) add(variant, common);
      return;
    }
    const merged = merge(shared, schema);
    const values = "const" in merged ? [merged.const] : merged.enum;
    if (values) {
      for (const value of values) found.literals.set(show(value), value);
      return;
    }
    const kinds = Array.isArray(merged.type) ? merged.type : merged.type ? [merged.type] : merged.properties ? ["object"] : [];
    if (!kinds.length) {
      const unread = Object.keys(merged).find((key) => !IGNORED.has(key) && !key.startsWith("x-") && !HANDLED.has(key));
      if (unread) throw new Error(`the check does not read ${unread}; teach it before using it`);
      if (Object.keys(merged).some((key) => !["default", "$defs"].includes(key) && HANDLED.has(key))) {
        throw new Error(`a schema without a type: ${show(merged).slice(0, 120)}`);
      }
      return void (found.any = true);
    }
    for (const kind of kinds) {
      if (!KINDS.includes(kind)) throw new Error(`unsupported type ${kind}`);
      found.branches.push({ kind: kind === "integer" ? "number" : kind, integer: kind === "integer", schema: { ...merged, type: kind } });
    }
  };
  add(schema, inherited);
  return found;
}

function strip(schema) {
  const kept = {};
  for (const [key, value] of Object.entries(schema)) if (!IGNORED.has(key) && !key.startsWith("x-")) kept[key] = value;
  return kept;
}

function merge(shared, variant) {
  const merged = { ...shared, ...variant };
  if (shared.properties || variant.properties) {
    merged.properties = { ...shared.properties, ...variant.properties };
    merged.required = [...(shared.required ?? []), ...(variant.required ?? [])];
  }
  return merged;
}

/** The property whose constant value tells object branches apart, if any. */
function tag(branch) {
  for (const [name, property] of Object.entries(branch.schema.properties ?? {})) {
    if (property && "const" in property) return `${name}=${show(property.const)}`;
  }
  return null;
}

function pair(old, now) {
  const pairs = [];
  const unmatched = { old: [], now: [] };
  for (const kind of new Set([...old, ...now].map((branch) => branch.kind))) {
    const before = old.filter((branch) => branch.kind === kind);
    const after = now.filter((branch) => branch.kind === kind);
    const take = (test, label) => {
      for (const branch of [...before]) {
        const match = after.find((other) => test(branch, other));
        if (!match) continue;
        pairs.push([branch, match, label(branch)]);
        before.splice(before.indexOf(branch), 1);
        after.splice(after.indexOf(match), 1);
      }
    };
    take((x, y) => show(x.schema) === show(y.schema), () => "");
    take((x, y) => tag(x) !== null && tag(x) === tag(y), (x) => ` (${tag(x)})`);
    if (before.length === 1 && after.length === 1) take(() => true, () => "");
    unmatched.old.push(...before);
    unmatched.now.push(...after);
  }
  return { pairs, unmatched };
}

/** `X | null`, as schemars writes an optional reference, split into X and null. */
function nullable(schema) {
  const variants = schema?.anyOf ?? schema?.oneOf;
  if (!variants || variants.length !== 2 || Object.keys(strip(schema)).length !== 1) return null;
  const inner = variants.find((variant) => variant.$ref);
  const none = variants.find((variant) => show(strip(variant)) === show({ type: "null" }));
  return inner && none ? inner : null;
}

class Comparison {
  constructor(oldDocument, newDocument) {
    Object.assign(this, { oldDocument, newDocument });
    this.breaking = new Set();
    this.additive = new Set();
    this.done = new Set();
  }

  note(breaking, path, what) {
    (breaking ? this.breaking : this.additive).add(`${path}: ${what}`);
  }

  schema(old, now, direction, path) {
    const input = direction === "input";
    const [x, y] = [nullable(old), nullable(now)];
    if (x || y) {
      if (!x !== !y) this.note(input ? Boolean(x) : Boolean(y), path, y ? "now may be null" : "no longer null");
      return this.schema(x ?? old, y ?? now, direction, path);
    }
    // A shared definition is compared once per direction and reported by name.
    if (old?.$ref && now?.$ref) {
      const name = resolve(this.newDocument, now).name;
      const key = `${resolve(this.oldDocument, old).name}>${name}>${direction}`;
      if (this.done.has(key)) return;
      this.done.add(key);
      path = name;
    }
    const before = alternatives(this.oldDocument, old);
    const after = alternatives(this.newDocument, now);
    if (path === "EnvelopeVersion") return; // The version is checked on its own.
    if (before.any || after.any) {
      if (before.any && after.any) return;
      return this.note(input ? before.any : after.any, path, after.any ? "now any value" : "no longer any value");
    }
    for (const [key, value] of before.literals) {
      if (after.literals.has(key)) continue;
      const covered = after.branches.some((branch) => branch.kind === kindOf(value) && !branch.schema.pattern);
      this.note(!(input && covered), path, `value ${key} removed`);
    }
    for (const key of after.literals.keys()) if (!before.literals.has(key)) this.note(false, path, `value ${key} added`);
    const { pairs, unmatched } = pair(before.branches, after.branches);
    for (const branch of unmatched.old) {
      this.note(true, path, `${branch.kind}${tag(branch) ? ` (${tag(branch)})` : ""} no longer ${input ? "accepted" : "sent"}`);
    }
    for (const branch of unmatched.now) {
      // A new variant of a tagged union reads like a new value; a new JSON kind does not.
      const variant = tag(branch) && before.branches.some((other) => other.kind === branch.kind && tag(other));
      this.note(!input && !variant, path, `${branch.kind}${tag(branch) ? ` (${tag(branch)})` : ""} now ${input ? "accepted" : "sent"}`);
    }
    for (const [old, now, label] of pairs) this.branch(old, now, direction, `${path}${label}`);
  }

  branch(old, now, direction, path) {
    const input = direction === "input";
    const a = old.schema;
    const b = now.schema;
    if (old.integer !== now.integer) this.note(input ? old.integer === false : now.integer === false, path, now.integer ? "now whole numbers only" : "now any number");
    for (const key of new Set([...Object.keys(a), ...Object.keys(b)])) {
      if (!IGNORED.has(key) && !key.startsWith("x-") && !HANDLED.has(key)) throw new Error(`${path}: the check does not read ${key}; teach it before using it`);
    }
    for (const key of ["pattern", "format"]) {
      if (show(a[key]) !== show(b[key])) this.note(true, path, `${key} ${show(a[key])} → ${show(b[key])}`);
    }
    if (input && show(a.default) !== show(b.default)) this.note(true, path, `default ${show(a.default)} → ${show(b.default)}`);
    for (const [keys, tighter] of [
      [UPPER, (x, y) => y < x],
      [LOWER, (x, y) => y > x],
    ]) {
      for (const key of keys) {
        if (a[key] === b[key]) continue;
        const narrowed = b[key] !== undefined && (a[key] === undefined || tighter(a[key], b[key]));
        this.note(input ? narrowed : !narrowed, path, `${key} ${a[key] ?? "none"} → ${b[key] ?? "none"}`);
      }
    }
    if (old.kind === "object") this.object(a, b, direction, path);
    if (old.kind === "array") {
      if (a.items !== undefined || b.items !== undefined) this.schema(a.items ?? true, b.items ?? true, direction, `${path}[]`);
      const length = Math.max(a.prefixItems?.length ?? 0, b.prefixItems?.length ?? 0);
      for (let index = 0; index < length; index++) {
        const [x, y] = [a.prefixItems?.[index], b.prefixItems?.[index]];
        if (x === undefined || y === undefined) this.note(true, path, `item ${index} ${x === undefined ? "added" : "removed"}`);
        else this.schema(x, y, direction, `${path}[${index}]`);
      }
    }
  }

  object(a, b, direction, path) {
    const input = direction === "input";
    const required = [new Set(a.required ?? []), new Set(b.required ?? [])];
    const before = a.properties ?? {};
    const after = b.properties ?? {};
    for (const name of Object.keys(before)) {
      if (!(name in after)) this.note(true, path, `field ${name} removed`);
    }
    for (const name of Object.keys(after)) {
      if (name in before) continue;
      const needed = required[1].has(name);
      this.note(input && needed, path, `${needed ? "required" : "optional"} field ${name} added`);
    }
    for (const name of Object.keys(before)) {
      if (!(name in after)) continue;
      const [was, is] = [required[0].has(name), required[1].has(name)];
      if (was !== is) this.note(input ? is : was, path, `field ${name} now ${is ? "required" : "optional"}`);
      this.schema(before[name], after[name], direction, `${path}.${name}`);
    }
    const [x, y] = [a.additionalProperties, b.additionalProperties];
    if (show(x) === show(y)) return;
    if (typeof x === "object" && typeof y === "object") return this.schema(x, y, direction, `${path}[*]`);
    const open = (value) => value !== false;
    if (open(x) !== open(y)) this.note(input ? !open(y) : open(y), path, open(y) ? "now takes other fields" : "now refuses other fields");
    else this.note(true, path, "unrecognised change to additionalProperties");
  }
}

function kindOf(value) {
  if (value === null) return "null";
  if (Array.isArray(value)) return "array";
  return typeof value === "number" ? "number" : typeof value;
}

/** Items matched by name; a subcommand goes unnamed when its command came or went. */
function named(old, now, label, each) {
  const result = { breaking: [], additive: [] };
  const before = new Map(old.map((item) => [item.name, item]));
  const after = new Map(now.map((item) => [item.name, item]));
  const parent = (name) => name.split(" ").slice(0, -1).join(" ");
  const alone = (name, missing) => !parent(name) || !missing.has(parent(name));
  const gone = new Set([...before.keys()].filter((name) => !after.has(name)));
  const fresh = new Set([...after.keys()].filter((name) => !before.has(name)));
  for (const name of gone) if (alone(name, gone)) result.breaking.push(`${label} ${name} removed`);
  for (const name of fresh) if (alone(name, fresh)) result.additive.push(`${label} ${name} added`);
  for (const [name, item] of before) if (after.has(name)) each(item, after.get(name), name);
  return result;
}

/** Every difference between two contracts, each breaking or additive. */
export function compare(base, head) {
  const breaking = new Set();
  const additive = new Set();
  const run = (oldDocument, newDocument, old, now, direction, path) => {
    const comparison = new Comparison(oldDocument, newDocument);
    comparison.schema(old, now, direction, path);
    for (const line of comparison.breaking) breaking.add(line);
    for (const line of comparison.additive) additive.add(line);
  };
  const collect = (result) => {
    for (const line of result.breaking) breaking.add(line);
    for (const line of result.additive) additive.add(line);
  };

  const golden = (engine) => {
    const found = resolve(engine, engine.properties?.case).schema?.properties;
    if (!found?.request || !found?.library || !found?.expected || !engine.properties?.exit_code) {
      throw new Error("the engine schema no longer has case.request, case.library, case.expected and exit_code");
    }
    return { ...found, exit_code: engine.properties.exit_code };
  };
  const [old, now] = [golden(base.engine), golden(head.engine)];
  for (const [field, direction] of [
    ["request", "input"],
    ["library", "output"],
    ["expected", "output"],
    ["exit_code", "output"],
  ]) {
    run(base.engine, head.engine, old[field], now[field], direction, `engine ${field}`);
  }

  const methods = (cli) => cli.data.map((method) => ({ ...method, name: method.method }));
  collect(
    named(methods(base.cli), methods(head.cli), "method", (a, b, name) => {
      run(a.params, b.params, a.params, b.params, "input", `method ${name} params`);
      run(a.result, b.result, a.result, b.result, "output", `method ${name} result`);
    }),
  );
  collect(
    named(base.mcp, head.mcp, "tool", (a, b, name) => {
      run(a.inputSchema, b.inputSchema, a.inputSchema, b.inputSchema, "input", `tool ${name} input`);
      run(a.outputSchema ?? true, b.outputSchema ?? true, a.outputSchema ?? true, b.outputSchema ?? true, "output", `tool ${name} output`);
    }),
  );

  const commands = (surface) => [...surface.commands].map(([name, command]) => ({ name, ...command }));
  collect(
    named(commands(base.surface), commands(head.surface), "command", (a, b, name) => {
      const label = name === "*" ? "every command" : `command ${name}`;
      // Positional names are only labels; a required new one is not visible here.
      if (b.positionals < a.positionals) breaking.add(`${label}: positional arguments ${a.positionals} → ${b.positionals}`);
      if (b.positionals > a.positionals) additive.add(`${label}: positional arguments ${a.positionals} → ${b.positionals}`);
      for (const [option, value] of a.options) {
        if (!b.options.has(option)) breaking.add(`${label}: option ${option} removed`);
        else if (b.options.get(option) !== value) breaking.add(`${label}: option ${option} ${value ? "no longer takes" : "now takes"} a value`);
      }
      for (const option of b.options.keys()) if (!a.options.has(option)) additive.add(`${label}: option ${option} added`);
    }),
  );
  for (const [code, exit] of base.surface.exits) {
    const now = head.surface.exits.get(code);
    if (now === undefined) breaking.add(`error ${code} removed`);
    else if (now !== exit) breaking.add(`error ${code}: exit ${exit} → ${now}`);
  }
  for (const code of head.surface.exits.keys()) if (!base.surface.exits.has(code)) additive.add(`error ${code} added`);
  return { breaking: [...breaking].sort(), additive: [...additive].sort() };
}

// --- Deciding ----------------------------------------------------------------

/**
 * THE 1.0 SWITCH. Before the stable 1.0 the contract is unstable: every
 * difference is reported and nothing fails (decision 0028). Set this to true
 * at 1.0 to make a breaking difference, or a contract the check cannot read,
 * fail land.sh and CI.
 */
export const BLOCKING = false;

/** The differences as a report, and whether they fail. */
export function verdict(base, head, blocking = BLOCKING) {
  const { breaking, additive } = compare(base, head);
  const list = (lines) => (lines.length ? lines.map((line) => `  ${line}`).join("\n") : "  none");
  const report = `Breaking:\n${list(breaking)}\nAdditive:\n${list(additive)}`;
  return { breaking, additive, report, fails: blocking && breaking.length > 0 };
}

// --- Running -----------------------------------------------------------------

const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 << 20 });

function newestRelease() {
  const tag = git("tag", "--list", "v[0-9]*", "--sort=-v:refname").split("\n")[0].trim();
  if (!tag) throw new Error("no release tag (v*) here to compare with; fetch the newest one: git fetch origin tag vX.Y.Z");
  return tag;
}

function main(argv) {
  const at = argv.indexOf("--base");
  const base = at >= 0 ? argv[at + 1] : newestRelease();
  if (!base) throw new Error("--base needs a commit or tag");
  if (git("rev-parse", "--is-shallow-repository").trim() === "false") {
    try {
      git("merge-base", "--is-ancestor", base, "HEAD");
    } catch {
      throw new Error(`${base} is not in this branch's history; rebase onto origin/main and rerun.`);
    }
  }
  const files = (read) => Object.fromEntries(FILES.map((path) => [path, read(path)]));
  const before = contract(files((path) => git("show", `${base}:${path}`)));
  const after = contract(files((path) => readFileSync(join(root, path), "utf8")));
  const { breaking, additive, report, fails } = verdict(before, after);
  console.log(`The contract against ${base}: ${breaking.length} breaking, ${additive.length} additive.\n${report}`);
  if (fails) process.exitCode = 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`Contract report skipped: ${error.message}`);
    if (BLOCKING) process.exitCode = 1;
  }
}

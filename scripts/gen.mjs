#!/usr/bin/env node
// Regenerate every file derived from the Rust code (decision 0037):
//   node scripts/gen.mjs           # write them
//   node scripts/gen.mjs --check   # fail, naming each one, if any is stale
// Each crate writes its own files from an ignored test into one temporary
// folder; this script places them, and turns the desktop's contract into
// TypeScript.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/** The ignored test in each crate that writes its generated files. */
export const WRITERS = [
  ["ibis-core", ["--test", "engine_contract"], "write_schema_snapshot"],
  ["ibis-engine", ["--lib"], "mcp::tools::write_tool_list"],
  ["ibis", ["--lib"], "generated::write_generated"],
  ["ibis-desktop", ["--bin", "ibis-desktop"], "bindings::tests::export_contract"],
];

const BEGIN = "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->";
const END = "<!-- End of generated options. -->";

/** What each derived file should hold, from the folder the writers filled. */
export function derived(folder, read = (path) => readFileSync(join(root, path), "utf8")) {
  const made = (name) => readFileSync(join(folder, name), "utf8");
  const cli = read("docs/cli.md");
  const start = cli.indexOf(BEGIN);
  const end = cli.indexOf(END);
  if (start < 0 || end < start) throw new Error(`docs/cli.md needs the lines\n${BEGIN}\n${END}`);
  return {
    "fixtures/engine-contract.schema.json": made("engine-contract.schema.json"),
    "fixtures/mcp-tools.json": made("mcp-tools.json"),
    "fixtures/cli-schema.json": made("cli-schema.json"),
    "docs/cli.md": `${cli.slice(0, start)}${BEGIN}\n${made("cli-options.md")}${cli.slice(end)}`,
    "apps/desktop/src/bindings.ts": bindings(JSON.parse(made("desktop-contract.json"))),
  };
}

// --- JSON Schema, as schemars writes it, to TypeScript ---------------------

const identifier = /^[A-Za-z_$][\w$]*$/;
const property = (name) => (identifier.test(name) ? name : JSON.stringify(name));

function doc(text, indent = "") {
  if (!text) return "";
  const lines = text.trim().split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

function union(parts) {
  const unique = [...new Set(parts)];
  return unique.length === 1 ? unique[0] : unique.join(" | ");
}

function reference(ref) {
  const name = ref.replace(/^#\/\$defs\//, "");
  if (name === ref) throw new Error(`unsupported $ref ${ref}`);
  return name;
}

/** One schema as a TypeScript type. */
export function type(schema, indent = "") {
  if (schema === true || schema === undefined || schema === null) return "unknown";
  if (schema === false) return "never";
  if (schema.$ref) return reference(schema.$ref);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return union(schema.enum.map((value) => JSON.stringify(value)));
  for (const keyword of ["oneOf", "anyOf"]) {
    if (!schema[keyword]) continue;
    // Shared properties (an internally tagged enum's) apply to every variant.
    const { [keyword]: variants, description: _, ...shared } = schema;
    return union(variants.map((variant) => type(Object.keys(shared).length ? merge(shared, variant) : variant, indent)));
  }
  if (schema.allOf) return schema.allOf.map((part) => type(part, indent)).join(" & ");
  const kinds = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (kinds.length > 1) return union(kinds.map((kind) => type({ ...schema, type: kind }, indent)));
  switch (kinds[0]) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      if (schema.prefixItems) return `[${schema.prefixItems.map((item) => type(item, indent)).join(", ")}]`;
      return list(type(schema.items, indent));
    case "object":
    case undefined:
      return schema.properties || kinds[0] ? object(schema, indent) : "unknown";
    default:
      throw new Error(`unsupported type ${schema.type}`);
  }
}

const list = (element) => (/^[\w"]+$/.test(element) ? `${element}[]` : `(${element})[]`);

function merge(shared, variant) {
  const merged = { ...shared, ...variant };
  if (shared.properties || variant.properties) {
    merged.type = "object";
    merged.properties = { ...shared.properties, ...variant.properties };
    merged.required = [...(shared.required ?? []), ...(variant.required ?? [])];
  }
  return merged;
}

function object(schema, indent) {
  const properties = Object.entries(schema.properties ?? {});
  const extra = schema.additionalProperties;
  if (properties.length === 0) {
    if (extra === false) return "Record<string, never>";
    return `{ [key: string]: ${extra && extra !== true ? type(extra, indent) : "unknown"} }`;
  }
  const required = new Set(schema.required ?? []);
  const inner = `${indent}\t`;
  const lines = properties.map(
    ([name, value]) =>
      `${doc(value.description, inner)}${inner}${property(name)}${required.has(name) ? "" : "?"}: ${type(value, inner)};`,
  );
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/** The desktop's commands, constants and types as `src/bindings.ts`. */
export function bindings(contract) {
  const definitions = { ...contract.output };
  for (const [name, schema] of Object.entries(contract.input)) {
    if (name in definitions && JSON.stringify(definitions[name]) !== JSON.stringify(schema)) {
      throw new Error(`${name} differs between what the app sends and what it receives; give the input its own type`);
    }
    definitions[name] = schema;
  }
  const commands = contract.commands.map(({ name, docs, args, returns }) => {
    const camel = name.replace(/_(.)/g, (_, letter) => letter.toUpperCase());
    const parameters = args.map(([arg, schema]) => `${arg}: ${type(schema, "\t")}`).join(", ");
    const payload = args.length ? `, { ${args.map(([arg]) => arg).join(", ")} }` : "";
    const result = returns === null ? "void" : type(returns, "\t");
    return `${doc(docs, "\t")}\t${camel}: (${parameters}) => __TAURI_INVOKE<${result}>("${name}"${payload}),\n`;
  });
  const constants = Object.entries(contract.constants).map(
    ([name, value]) => `export const ${name} = ${JSON.stringify(value)} as const;\n`,
  );
  const types = Object.keys(definitions)
    .sort()
    .map((name) => `${doc(definitions[name].description)}export type ${name} = ${type(definitions[name])};\n`);
  return [
    "// Generated by `node scripts/gen.mjs` from the desktop's commands. Do not edit.\n\n",
    'import { invoke as __TAURI_INVOKE } from "@tauri-apps/api/core";\n\n',
    `export const commands = {\n${commands.join("")}};\n\n`,
    constants.join("\n"),
    "\n",
    types.join("\n"),
  ].join("");
}

// --- Running ----------------------------------------------------------------

function run(check) {
  const folder = mkdtempSync(join(tmpdir(), "ibis-gen-"));
  try {
    for (const [crate, target, test] of WRITERS) {
      execFileSync("cargo", ["test", "-q", "-p", crate, "--locked", ...target, test, "--", "--ignored", "--exact"], {
        cwd: root,
        env: { ...process.env, IBIS_GEN_DIR: folder },
        stdio: ["ignore", "ignore", "inherit"],
      });
    }
    const stale = [];
    for (const [path, text] of Object.entries(derived(folder))) {
      let current = null;
      try {
        current = readFileSync(join(root, path), "utf8");
      } catch {}
      if (current === text) continue;
      stale.push(path);
      if (!check) writeFileSync(join(root, path), text);
    }
    if (check && stale.length) {
      console.error(`Stale generated files; run node scripts/gen.mjs:\n${stale.map((path) => `  ${path}`).join("\n")}`);
      process.exitCode = 1;
    } else {
      console.log(stale.length ? `Wrote ${stale.join(", ")}` : "Every generated file is current.");
    }
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) run(process.argv.includes("--check"));

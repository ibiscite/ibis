import assert from "node:assert/strict";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { bindings, derived, type } from "./gen.mjs";

test("schemas become the TypeScript the app reads", () => {
  assert.equal(type({ type: "string", enum: ["a", "b"] }), '"a" | "b"');
  assert.equal(type({ type: ["string", "null"] }), "string | null");
  assert.equal(type({ type: "array", items: { $ref: "#/$defs/Row" } }), "Row[]");
  assert.equal(type({ type: "object", additionalProperties: { type: "integer" } }), "{ [key: string]: number }");
  assert.equal(type({ type: "array", prefixItems: [{ type: "integer" }, { type: "boolean" }] }), "[number, boolean]");
  // An internally tagged enum: the tag and each variant's own fields.
  assert.equal(
    type({ oneOf: [
      { type: "object", properties: { kind: { const: "removed" }, id: { type: "string" } }, required: ["kind", "id"] },
      { type: "object", properties: { kind: { const: "reset" } }, required: ["kind"] },
    ] }),
    '{\n\tkind: "removed";\n\tid: string;\n} | {\n\tkind: "reset";\n}',
  );
  assert.equal(type({ type: "object", properties: { note: { type: "string" } } }), "{\n\tnote?: string;\n}");
});

test("engine record identifiers are opaque to display code", () => {
  const opaque = type({ type: "string", "x-ibis-opaque": "RecordId" });
  assert.match(opaque, /readonly/);
  assert.doesNotMatch(opaque, /\bstring\b/);
});

test("commands keep their wire names and throw their errors", () => {
  const text = bindings({
    commands: [
      { name: "use_sample_library", docs: "Samples.", args: [["enabled", { type: "boolean" }]], returns: { type: "null" }, error: { type: "string" } },
      { name: "choose_library", docs: "", args: [], returns: null, error: null },
    ],
    input: {},
    output: { Mode: { type: "string", enum: ["on"] } },
    constants: { DEFAULT_OUTPUT: "pandoc" },
  });
  assert.match(text, /\tuseSampleLibrary: \(enabled: boolean\) => __TAURI_INVOKE<null>\("use_sample_library", \{ enabled \}\),/);
  assert.match(text, /\tchooseLibrary: \(\) => __TAURI_INVOKE<void>\("choose_library"\),/);
  assert.match(text, /export const DEFAULT_OUTPUT = "pandoc" as const;/);
  assert.match(text, /export type Mode = "on";/);
});

test("a type that differs between sending and receiving is refused, not guessed", () => {
  assert.throws(
    () => bindings({ commands: [], input: { Row: { type: "string" } }, output: { Row: { type: "integer" } }, constants: {} }),
    /Row differs/,
  );
});

test("the options and error sections both update without replacing surrounding prose", () => {
  const folder = mkdtempSync(join(tmpdir(), "ibis-gen-test-"));
  for (const name of ["engine-contract.schema.json", "mcp-tools.json", "cli-schema.json"]) writeFileSync(join(folder, name), "{}\n");
  writeFileSync(join(folder, "cli-options.md"), "### Every option\n");
  writeFileSync(join(folder, "cli-errors.json"), '[{"code":"not-found","exit":4}]');
  writeFileSync(join(folder, "desktop-contract.json"), JSON.stringify({ commands: [], input: {}, output: {}, constants: {} }));
  const begin = "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->";
  const end = "<!-- End of generated options. -->";
  const source = `# Before\n${begin}\nold\n${end}\n<!-- gen:errors -->\nold errors\n<!-- /gen:errors -->\nAfter\n`;
  try {
    const files = derived(folder, () => source);
    assert.equal(files["docs/cli.md"], `# Before\n${begin}\n### Every option\n${end}\n<!-- gen:errors -->\n\n| Exit | Error code |\n| --- | --- |\n| 4 | \`not-found\` |\n\n<!-- /gen:errors -->\nAfter\n`);
    assert.equal(derived(folder, () => files["docs/cli.md"])["docs/cli.md"], files["docs/cli.md"]);
    for (const broken of ["no markers", source.replace(end, ""), source.replace("<!-- gen:errors -->", ""), `${source}\n<!-- gen:errors -->`]) {
      assert.throws(() => derived(folder, () => broken), /exactly one ordered pair/);
    }
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
});

test("headless generation needs no desktop contract and leaves desktop files out", () => {
  const folder = mkdtempSync(join(tmpdir(), "ibis-gen-test-"));
  try {
    for (const name of ["engine-contract.schema.json", "mcp-tools.json", "cli-schema.json"]) writeFileSync(join(folder, name), "{}\n");
    writeFileSync(join(folder, "cli-options.md"), "Options\n");
    writeFileSync(join(folder, "cli-errors.json"), "[]");
    const begin = "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->";
    const end = "<!-- End of generated options. -->";
    const files = derived(folder, () => `${begin}\n${end}\n<!-- gen:errors -->\n<!-- /gen:errors -->`, true);
    assert.deepEqual(Object.keys(files), [
      "fixtures/engine-contract.schema.json", "fixtures/mcp-tools.json", "fixtures/cli-schema.json", "docs/cli.md",
    ]);
    assert.equal(files["fixtures/engine-contract.schema.json"], "{}\n");
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
});

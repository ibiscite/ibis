import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { cliSurface, compare, contract, FILES, verdict } from "./contract-compat.mjs";

const root = new URL("..", import.meta.url);

// An invented contract, small enough to read: one method, one tool, two commands.
function make({ version = 1, params, result, input, output, request, expected, commands, errors } = {}) {
  const engine = {
    type: "object",
    properties: { case: { $ref: "#/$defs/Case" }, exit_code: { $ref: "#/$defs/Exit" } },
    $defs: {
      EnvelopeVersion: { type: "integer", const: version },
      Exit: { type: "integer", enum: [0, 2] },
      Case: {
        type: "object",
        properties: {
          request: request ?? { $ref: "#/$defs/Request" },
          library: { type: "object" },
          expected: expected ?? { type: "object", properties: { ibis: { $ref: "#/$defs/EnvelopeVersion" }, ok: { type: "boolean" } }, required: ["ibis", "ok"] },
        },
      },
      Request: { type: "object", properties: { keys: { type: "array", items: { type: "string" }, maxItems: 10 } }, required: ["keys"], additionalProperties: false },
    },
  };
  const library = {
    $defs: { Kind: { description: "Which library.", enum: ["personal", "group"], type: "string" } },
    oneOf: [{ $ref: "#/$defs/Kind" }],
  };
  const cli = {
    ibis: version,
    ok: true,
    data: [
      {
        contract: version,
        method: "search",
        params: params ?? { type: "object", properties: { words: { type: "string" }, library: { anyOf: [{ $ref: "#/$defs/Kind" }, { type: "null" }] } }, required: ["words"], $defs: library.$defs, additionalProperties: false },
        result: result ?? { type: "object", properties: { hits: { type: "array", items: { type: "string" } }, total: { type: "integer" } }, required: ["hits", "total"] },
      },
    ],
  };
  const mcp = [
    {
      name: "cite",
      inputSchema: input ?? { type: "object", properties: { keys: { type: "array", items: { type: "string" } }, style: { type: ["string", "null"] } }, required: ["keys"] },
      outputSchema: output ?? { type: "object", properties: { text: { type: "string" } }, required: ["text"] },
    },
  ];
  const options = (commands ?? { "*": ["--json"], search: ["--limit N", "--keys"], writings: [], "writings list": [] });
  const markdown = [
    "Intro.",
    "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->",
    ...Object.entries(options).flatMap(([name, rows]) => [
      name === "*" ? "**Every command** also takes:" : `**\`ibis ${name}\`**: Does a thing`,
      "",
      "| Option | Does |",
      "| --- | --- |",
      ...rows.map((row) => `| \`${row}\` | Something |`),
      "",
    ]),
    "<!-- End of generated options. -->",
    "<!-- gen:errors -->",
    ...Object.entries(errors ?? { usage: 2, internal: 70 }).map(([code, exit]) => `| ${exit} | \`${code}\` |`),
    "<!-- /gen:errors -->",
  ].join("\n");
  return contract({
    [FILES[0]]: JSON.stringify(engine),
    [FILES[1]]: JSON.stringify(cli),
    [FILES[2]]: JSON.stringify(mcp),
    [FILES[3]]: markdown,
  });
}

const breaks = (...entries) => ({ breaks: entries.map(([contract, change]) => ({ contract, change, why: "Invented." })) });

test("an unchanged contract has no differences", () => {
  assert.deepEqual(compare(make(), make()), { breaking: [], additive: [] });
});

test("the real contract files parse and agree on one version", () => {
  const texts = Object.fromEntries(FILES.map((path) => [path, readFileSync(new URL(path, root), "utf8")]));
  const current = contract(texts);
  assert.ok(Number.isInteger(current.version));
  assert.ok(current.surface.commands.get("search").has("--limit"));
  assert.deepEqual(compare(current, current), { breaking: [], additive: [] });
});

test("additive changes pass under the same version", () => {
  const base = make();
  const head = make({
    // An optional input field, an output field clients may ignore and an output value they treat as unknown.
    params: { ...base.cli.data[0].params, properties: { ...base.cli.data[0].params.properties, limit: { type: "integer" } } },
    result: { type: "object", properties: { hits: { type: "array", items: { type: "string" } }, total: { type: "integer" }, revision: { type: "string" } }, required: ["hits", "total", "revision"] },
    output: { type: "object", properties: { text: { type: "string" }, kind: { enum: ["note"] } }, required: ["text"] },
    commands: { "*": ["--json", "--width N"], search: ["--limit N", "--keys", "--shorthand"], writings: [], "writings list": [], share: ["--to PATH"] },
    errors: { usage: 2, internal: 70, "lookup-off": 3 },
  });
  const { errors, breaking, additive } = verdict(base, head, breaks());
  assert.deepEqual(errors, []);
  assert.deepEqual(breaking, []);
  assert.deepEqual(additive, [
    "command search: option --shorthand added",
    "command share added",
    "error lookup-off added",
    "every command: option --width added",
    "method search params: optional field limit added",
    "method search result: required field revision added",
    "tool cite output: optional field kind added",
  ]);
});

test("an enumeration rewritten as one of the same values is no change", () => {
  const head = make();
  head.cli.data[0].params.$defs.Kind = { oneOf: [{ enum: ["personal"], type: "string" }, { const: "group", type: "string", description: "A group." }] };
  assert.deepEqual(compare(make(), head), { breaking: [], additive: [] });
});

/** A contract with one breaking change of each kind. */
function broken(version = 1) {
  const head = make({
    version,
    // Newly required field, removed field and a narrowed type, all on input.
    input: { type: "object", properties: { keys: { type: "array", items: { type: "string" } }, style: { type: "string" }, locale: { type: "string" } }, required: ["keys", "locale"] },
    // A result that may now be null, and a field gone from it.
    result: { type: "object", properties: { hits: { type: ["array", "null"], items: { type: "string" } } }, required: ["hits"] },
    commands: { "*": [], search: ["--limit N", "--keys VALUE"], projects: [], "projects list": [] },
    errors: { usage: 2, internal: 71 },
  });
  // A renamed value, and a tighter limit on what a request may hold.
  head.cli.data[0].params.$defs.Kind = { enum: ["user", "group"], type: "string" };
  head.engine.$defs.Request.properties.keys.maxItems = 5;
  head.mcp.push({ name: "styles", inputSchema: { type: "object" } });
  head.cli.data.push({ contract: version, method: "share", params: { type: "object" }, result: { type: "object" } });
  return head;
}

const BROKEN = [
  "Kind: value \"personal\" removed",
  "Request.keys: maxItems 10 → 5",
  "command search: option --keys now takes a value",
  "command writings removed",
  "error internal: exit 70 → 71",
  "every command: option --json removed",
  "method search result.hits: null now sent",
  "method search result: field total removed",
  "tool cite input.style: null no longer accepted",
  "tool cite input: required field locale added",
];

test("every kind of breaking change fails under the same version", () => {
  const base = make();
  const head = broken();
  const { errors, breaking } = verdict(base, head, breaks());
  assert.deepEqual(breaking, BROKEN);
  assert.equal(errors.length, 1);
  assert.match(errors[0], /Raise CONTRACT_VERSION to 2 and list each one in fixtures\/contract-breaks\.json under contract 2/);
  for (const line of BROKEN) assert.ok(errors[0].includes(`  ${line}`), line);
});

test("a removed method or tool is breaking", () => {
  const head = make();
  head.cli.data = [];
  head.mcp = [];
  assert.deepEqual(compare(make(), head).breaking, ["method search removed", "tool cite removed"]);
});

test("a break passes when the version is raised and the break is listed", () => {
  const listed = breaks(...BROKEN.map((line) => [2, line]));
  assert.deepEqual(verdict(make(), broken(2), listed).errors, []);
});

test("a raised version still fails on an unlisted, stale or misplaced break", () => {
  const [first, ...rest] = BROKEN;
  const unlisted = verdict(make(), broken(2), breaks(...rest.map((line) => [2, line]))).errors;
  assert.equal(unlisted.length, 1);
  assert.match(unlisted[0], /not listed in fixtures\/contract-breaks\.json under contract 2:\n {2}Kind: value "personal" removed$/);

  const stale = verdict(make(), broken(2), breaks(...BROKEN.map((line) => [2, line]), [2, "tool gone removed"])).errors;
  assert.deepEqual(stale, ["fixtures/contract-breaks.json lists a break this change no longer makes: tool gone removed"]);

  const early = verdict(make(), broken(2), breaks(...BROKEN.map((line) => [2, line]), [3, first])).errors;
  assert.deepEqual(early, [`fixtures/contract-breaks.json lists a break for contract 3, but the contract is 2: ${first}`]);
});

test("the version moves by exactly one, and only with a listed break", () => {
  assert.match(verdict(make(), broken(3), breaks(...BROKEN.map((line) => [3, line]))).errors[0], /by one per release: 1 → 2, not 3/);
  assert.match(verdict(make({ version: 2 }), make(), breaks()).errors[0], /went down, from 2 to 1/);
  assert.deepEqual(verdict(make(), make({ version: 2 }), breaks()).errors, ["The contract version was raised to 2 with no break listed for it in fixtures/contract-breaks.json."]);
  const unraised = verdict(make(), make(), breaks([2, "Kind: value \"personal\" removed"])).errors;
  assert.deepEqual(unraised, [`fixtures/contract-breaks.json lists a break for contract 2, but the contract is 1: Kind: value "personal" removed`]);
});

test("breaks listed for released versions are history", () => {
  assert.deepEqual(verdict(make({ version: 2 }), make({ version: 2 }), breaks([1, "old"], [2, "older"])).errors, []);
});

test("each entry gives its version, the change as printed and why", () => {
  const { errors } = verdict(make(), make(), { breaks: [{ contract: 2, change: "x" }] });
  assert.match(errors[0], /each entry needs a whole-number contract, the change as printed, and why/);
});

test("the files must agree on the contract version", () => {
  const texts = Object.fromEntries(FILES.map((path) => [path, readFileSync(new URL(path, root), "utf8")]));
  const cli = JSON.parse(texts[FILES[1]]);
  cli.data[0].contract = cli.ibis + 1;
  assert.throws(() => contract({ ...texts, [FILES[1]]: JSON.stringify(cli) }), /disagree on the contract version/);
});

test("the CLI's options and exit codes are read from its generated reference", () => {
  const { commands, exits } = cliSurface(
    [
      "<!-- Generated by node scripts/gen.mjs from the command line's own options. -->",
      "**Every command** also takes:",
      "| `--json` | JSON |",
      "**`ibis cite`**: Write a citation",
      "| `KEY…` | Keys |",
      "| `--format FORMAT` | Output |",
      "<!-- End of generated options. -->",
      "<!-- gen:errors -->",
      "| Exit | Error code |",
      "| --- | --- |",
      "| 2 | `usage` |",
      "<!-- /gen:errors -->",
    ].join("\n"),
  );
  assert.deepEqual([...commands.get("*")], [["--json", false]]);
  assert.deepEqual([...commands.get("cite")], [["--format", true]]);
  assert.deepEqual([...exits], [["usage", 2]]);
  assert.throws(() => cliSurface("no markers"), /docs\/cli\.md needs/);
});
